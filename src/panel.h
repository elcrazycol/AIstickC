// Веб-панель: HTTP-сервер на стике.
//
// Панель поднимается только когда нужна — по пункту меню «Веб-панель». В
// простое её нет: сервер, сокеты и буфер страницы занимают память, которой и
// так немного, а TLS-сессии модели и распознавания держат по сорок килобайт.
//
// Сервер крутится отдельной задачей, а не в общем цикле: иначе на время
// ответа модели (это секунды блокирующей сети) панель замирала бы ровно в тот
// момент, когда в неё смотрят.
//
// Каждый запрос отмечается как активность: пока по панели ходят, стик не
// уходит в сон. Отметку ставит задача, а продлевает простой основной цикл —
// трогать состояние дисплея и Wi-Fi из чужой задачи нельзя.
#pragma once

#include <cstddef>
#include <string>

namespace panel {

// Поднять панель: сервер, код доступа, адрес для QR. false — не поднялась.
bool begin();

// Погасить панель: сервер выключается, память освобождается.
void end();

bool active();

// Заходил ли кто-нибудь на страницу с момента открытия. Нужно экрану: зелёный
// значит «на связи», жёлтый — «включена, но никто ещё не зашёл».
bool used();

// Адрес для QR и код доступа (4 цифры).
std::string url();
const char* code();

// Снимок истории для страницы: готовый JSON-массив реплик кладёт основной
// цикл, когда история меняется. Панель его только отдаёт.
void setHistory(const char* json);

// Отпустить снимок истории: он нужен только странице, а во время вопроса
// память нужнее TLS-рукопожатиям. Панель при этом остаётся поднятой.
void releaseHistory();

// Обслужить запросы, если они есть. Зовётся из общего цикла: отдельная задача
// стоила шесть килобайт стека, и этих килобайт как раз не хватало TLS-рукопожа-
// тию, когда сессии модели и распознавания уже открыты.
void poll();

// Был ли запрос к панели с прошлой проверки. Каждый запрос — это активность.
bool touched();

}  // namespace panel
