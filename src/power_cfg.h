// Сколько ждать перед глубоким сном — выбор пользователя.
//
// Числа и подписи — в pure/sleep_options.h; здесь только хранение в NVS и
// применение. Выбор переживает и выключение, и сам глубокий сон: настройки
// лежат во флеше.
#pragma once

#include <cstddef>
#include <cstdint>
#include <string>

namespace powercfg {

// Читает выбор из NVS. Значение не из списка (осталось от другой прошивки)
// превращается в заводское.
void begin();

// Назад к заводскому — час.
void reset();

size_t choice();
std::string label();  // «1 час» — для меню

void next();  // следующая ступень по кругу

// Сколько миллисекунд простоя ждать перед глубоким сном.
// 0 — не спать никогда.
uint32_t sleepMs();

}  // namespace powercfg
